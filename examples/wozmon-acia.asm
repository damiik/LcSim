; Woz monitor ACIA adaptation supplied by the user (Ben Eater version).
; The leading byte pads the F000-based ROM; instructions are unchanged.
; WARIANT LF: terminator wiersza to $0A zamiast $0D - w NEXTCHAR (wprowadzanie)
; i w NEXTITEM (skan bufora po Enterze); terminal wysyla wylacznie LF.
.org $F000
.byte $00
.org $FF00

XAML=$24
XAMH=$25
STL=$26
STH=$27
L=$28
H=$29
YSAV=$2A
MODE=$2B
IN=$0200

ACIA_DATA=$5000
ACIA_STATUS=$5001
ACIA_CMD=$5002
ACIA_CTRL=$5003

RESET:
 LDA #$1F
 STA ACIA_CTRL
 LDA #$0B
 STA ACIA_CMD
 LDA #$1B
NOTCR:
 CMP #$08
 BEQ BACKSPACE
 CMP #$1B
 BEQ ESCAPE
 INY
 BPL NEXTCHAR

ESCAPE:
 LDA #$5C
 JSR ECHO
GETLINE:
 LDA #$0D
 JSR ECHO
 LDY #$01
BACKSPACE:
 DEY
 BMI GETLINE
NEXTCHAR:
 LDA ACIA_STATUS
 AND #$08
 BEQ NEXTCHAR
 LDA ACIA_DATA
 STA IN,Y
 JSR ECHO
 CMP #$0A ; LF -> CR+LF (Linux)
 BNE NOTCR
 LDY #$FF
 LDA #$00
 TAX
SETBLOCK:
 ASL
SETSTOR:
 ASL
 STA MODE
BLSKIP:
 INY
NEXTITEM:
 LDA IN,Y
 CMP #$0A; LF -> CR+LF (Linux)
 BEQ GETLINE
 CMP #$2E
 BCC BLSKIP
 BEQ SETBLOCK
 CMP #$3A
 BEQ SETSTOR
 CMP #$52
 BEQ RUN
 STX L
 STX H
 STY YSAV
NEXTHEX:
 LDA IN,Y
 EOR #$30
 CMP #$0A
 BCC DIG
 ADC #$88
 CMP #$FA
 BCC NOTHEX
DIG:
 ASL
 ASL
 ASL
 ASL
 LDX #$04
HEXSHIFT:
 ASL
 ROL L
 ROL H
 DEX
 BNE HEXSHIFT
 INY
 BNE NEXTHEX
NOTHEX:
 CPY YSAV
 BEQ ESCAPE
 BIT MODE
 BVC NOTSTOR
 LDA L
 STA (STL,X)
 INC STL
 BNE NEXTITEM
 INC STH
TONEXTITEM:
 JMP NEXTITEM
RUN:
 JMP (XAML)
NOTSTOR:
 BMI XAMNEXT
 LDX #$02
SETADR:
 LDA L-1,X
 STA STL-1,X
 STA XAML-1,X
 DEX
 BNE SETADR
NXTPRNT:
 BNE PRDATA
 LDA #$0D
 JSR ECHO
 LDA XAMH
 JSR PRBYTE
 LDA XAML
 JSR PRBYTE
 LDA #$3A
 JSR ECHO
PRDATA:
 LDA #$20
 JSR ECHO
 LDA (XAML,X)
 JSR PRBYTE
XAMNEXT:
 STX MODE
 LDA XAML
 CMP L
 LDA XAMH
 SBC H
 BCS TONEXTITEM
 INC XAML
 BNE MOD8CHK
 INC XAMH
MOD8CHK:
 LDA XAML
 AND #$07
 BPL NXTPRNT
PRBYTE:
 PHA
 LSR
 LSR
 LSR
 LSR
 JSR PRHEX
 PLA
PRHEX:
 AND #$0F
 ORA #$30
 CMP #$3A
 BCC ECHO
 ADC #$06
ECHO:
 ; LcSim ACIA accepts a byte immediately; no simulated baud-delay loop.
 PHA
 STA ACIA_DATA
 PLA
 RTS
.org $FFFA
.word $0F00
.word RESET
.word $0000
